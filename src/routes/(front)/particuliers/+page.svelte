		<br />
		<h3 class="h2-blue font-bold text-base">QU'EST-CE QU'UNE COOPÉRATIVE ARTISANALE ?</h3>
		<p>
			C'est une structure qui rassemble des artisans partageant des valeurs fortes et un
			savoir-faire reconnu. Différents corps de métier vont constituer la coopérative (maçonnerie,
			charpente, plomberie, électricité, couverture, peinture, menuiserie, et bien d'autres encore)
			afin de mutualiser leurs compétences, moyens et ressources, dans le but de proposer une offre
			de travaux complète, cohérente et bien coordonnée. C'est l'esprit collectif au service de
			votre projet.
		</p>
		<br />
		<h3 class="h2-blue font-bold text-base">QUI EST LA FFACB ?</h3>
		<p>
			La Fédération Française des Artisans Coopérateurs du Bâtiment (FFACB) est une Organisation
			Professionnelle Nationale créée en 1988 qui rassemble les coopératives d'artisans de
			productions et de services du bâtiment.
			<br />
			La FFACB agit comme un réseau fédérateur, apportant soutien, formation et accompagnement aux coopératives
			adhérentes.
		</p>

