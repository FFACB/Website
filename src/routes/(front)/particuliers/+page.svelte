		<h3 class="h2-blue font-bold text-base">
			UNE COORDINATION FACILITÉE ET DES INTERMÉDIAIRES LIMITÉS
		</h3>
		<p class="text-white">
			Les artisans se connaissent et ont l'habitude de travailler ensemble ce qui favorise la
			synergie, la fluidité du chantier mais surtout une bonne communication entre les intervenants.
			Le mouvement coopératif permet des intervenants majoritairement, voire exclusivement, associés
			de la coopérative. Les coopératives étant, en effet, légalement limitées dans l'intervention
			de sous-traitants afin de favoriser l'activité de ses membres.
		</p>

		<div class="w-max mt-8 p-4 pt-2 pb-2 font-bold text-white bg-red rounded-3xl">
			<strong>Résultats :</strong> moins d'intermédiaires, un meilleur suivi,<br /> une communication
			fluide et des chantiers plus sereins.
		</div>
		<br />
		<p class="text-white">
			Une coopérative repose sur un collectif d'artisans solidaires, ce qui limite les risques
			d'abandon de chantier liés à un acteur isolé. En cas de difficulté d'un membre, les autres
			prennent le relais. Le fonctionnement mutualisé protège votre projet.
		</p>
	</div>
